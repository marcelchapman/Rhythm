const be = (n: number) => {
  const b = Buffer.alloc(4);
  b.writeUInt32BE(n);
  return b;
};
const le = (n: number) => {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n);
  return b;
};
export function block(type: number, data: Uint8Array, last = false) {
  const h = Buffer.alloc(4);
  h[0] = type | (last ? 128 : 0);
  h.writeUIntBE(data.length, 1, 3);
  return Buffer.concat([h, data]);
}
export function commentBlock(values: [string, string][]) {
  const vendor = Buffer.from("Rio generated fixture");
  return Buffer.concat([
    le(vendor.length),
    vendor,
    le(values.length),
    ...values.flatMap(([k, v]) => {
      const s = Buffer.from(`${k}=${v}`);
      return [le(s.length), s];
    }),
  ]);
}
function crc(bytes: Uint8Array, bits: 8 | 16) {
  let value = 0;
  for (const byte of bytes) {
    value ^= byte << (bits - 8);
    for (let bit = 0; bit < 8; bit++)
      value =
        ((value << 1) ^
          (value & (1 << (bits - 1)) ? (bits === 8 ? 7 : 0x8005) : 0)) &
        ((1 << bits) - 1);
  }
  return value;
}
const count = 256;
export function pcmFixture() {
  const pcm = Buffer.alloc(count * 4);
  for (let n = 0; n < count; n++)
    for (let ch = 0; ch < 2; ch++)
      pcm.writeInt16LE(
        Math.round(Math.sin(((n + ch) * 2 * Math.PI * 440) / 48000) * 8192),
        n * 4 + ch * 2,
      );
  return pcm;
}
function audio() {
  const pcm = pcmFixture(),
    frames: Buffer[] = [];
  for (let frame = 0; frame < 2; frame++) {
    const h = Buffer.from([255, 248, 0x6a, 0x18, frame, 127]);
    const parts = [h, Buffer.from([crc(h, 8)])];
    for (let ch = 0; ch < 2; ch++) {
      const samples = Buffer.alloc(256);
      for (let n = 0; n < 128; n++)
        samples.writeInt16BE(
          pcm.readInt16LE((frame * 128 + n) * 4 + ch * 2),
          n * 2,
        );
      parts.push(Buffer.from([2]), samples); // Verbatim subframe, no wasted bits.
    }
    const data = Buffer.concat(parts),
      footer = Buffer.alloc(2);
    footer.writeUInt16BE(crc(data, 16));
    frames.push(Buffer.concat([data, footer]));
  }
  return Buffer.concat(frames);
}
export function pngFixture(color = 0) {
  function chunk(type: string, data: Buffer) {
    const body = Buffer.concat([Buffer.from(type), data]);
    let crc = 0xffffffff;
    for (const byte of body) {
      crc ^= byte;
      for (let bit = 0; bit < 8; bit++)
        crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
    return Buffer.concat([be(data.length), body, be((crc ^ 0xffffffff) >>> 0)]);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(4);
  header.writeUInt32BE(4, 4);
  header[8] = 8;
  header[9] = 2;
  const pixels = Buffer.alloc(4 * 13);
  for (let row = 0; row < 4; row++)
    for (let x = 0; x < 4; x++) pixels[row * 13 + 1 + x * 3 + color] = 200;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(pixels)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
