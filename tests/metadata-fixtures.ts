export function flacFixture(
  options: {
    entries?: [string, string][];
    pictures?: Buffer[];
    application?: boolean;
  } = {},
) {
  const stream = Buffer.alloc(34),
    payload = audio();
  stream.writeUInt16BE(128, 0);
  stream.writeUInt16BE(128, 2);
  stream.writeUIntBE(payload.length / 2, 4, 3);
  stream.writeUIntBE(payload.length / 2, 7, 3);
  stream.writeBigUInt64BE(
    (48000n << 44n) | (1n << 41n) | (15n << 36n) | BigInt(count),
    10,
  );
  createHash("md5").update(pcmFixture()).digest().copy(stream, 18);
  const blocks = [
    block(0, stream),
    block(4, commentBlock(options.entries ?? entries)),
  ];
  if (options.application !== false)
    blocks.push(block(2, Buffer.from("RLAB-unrelated-application-bytes")));
  for (const picture of options.pictures ?? []) blocks.push(block(6, picture));
  blocks.push(block(1, Buffer.alloc(32), true));
  return Buffer.concat([Buffer.from("fLaC"), ...blocks, payload]);
}
/** Independent test inspector: metadata offsets and raw audio bytes, no production parser. */
export function inspectFlac(bytes: Uint8Array) {
  const b = Buffer.from(bytes),
    blocks: { type: number; body: Buffer }[] = [];
  let at = 4;
  while (at < b.length) {
    const type = b[at] & 127,
      last = b[at] & 128,
      length = b.readUIntBE(at + 1, 3);
    blocks.push({ type, body: b.subarray(at + 4, at + 4 + length) });
    at += 4 + length;
    if (last) break;
  }
  return { blocks, audio: b.subarray(at) };
}
